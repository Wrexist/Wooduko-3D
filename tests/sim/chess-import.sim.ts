// Builds src/core/chessPuzzles.ts from the Lichess puzzle database (public domain, CC0):
// https://database.lichess.org/#puzzles. Ratings there come from millions of real attempts, so
// they match how hard a puzzle feels to people. Download lichess_db_puzzle.csv.zst, then:
//   LICHESS_ZST=path/to/lichess_db_puzzle.csv.zst npm run chess:import   (a few minutes)
//
// Kept: well-tested puzzles (popular, many plays, a settled rating) with at most three of your
// moves, spread evenly over 400..2900 in 100-point bands and mixed by theme. Lichess gives the
// position before the opponent's last move; that move is played first, and Black-to-move
// positions are mirrored so you always play White.
import { createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { createZstdDecompress } from 'node:zlib';
import { describe, it } from 'vitest';
import { fromFen, makeMove } from '../../src/core/chess';
import { fullFen, mirrorFen, moveOf } from '../../src/core/chessTrain';

const PER_BAND = 60;
const PER_THEME = 14;
const LOW = 400;
const HIGH = 2900;
const NL = String.fromCharCode(10);

/** Lichess theme tags → ours, first match wins (most specific first). */
const THEMES: readonly [string, string][] = [
  ['mateIn1', 'mate1'],
  ['mateIn2', 'mate2'],
  ['mateIn3', 'mate3'],
  ['fork', 'fork'],
  ['pin', 'pin'],
  ['skewer', 'skewer'],
  ['discoveredAttack', 'discovered'],
  ['deflection', 'deflection'],
  ['sacrifice', 'sacrifice'],
  ['promotion', 'promotion'],
  ['hangingPiece', 'hanging'],
  ['endgame', 'endgame'],
];

const mirrorUci = (u: string): string => {
  const f = (s: string): string => s.charAt(0) + String(9 - Number(s.charAt(1)));
  return f(u.slice(0, 2)) + f(u.slice(2, 4)) + u.slice(4);
};

describe('chess puzzles from Lichess', () => {
  it('imports and writes src/core/chessPuzzles.ts', async () => {
    // the file opens with a 12-byte skippable frame (seek table) that Node's decoder rejects
    const path = process.env.LICHESS_ZST;
    if (!path) throw new Error('set LICHESS_ZST to the downloaded lichess_db_puzzle.csv.zst');
    const unzip = createZstdDecompress();
    const lines = createInterface({ input: createReadStream(path, { start: 12 }).pipe(unzip) });
    // later skippable frames end the stream early; the bands are full long before
    unzip.on('error', () => lines.close());
    const bands = new Map<number, { line: string; rating: number }[]>();
    const themeCount = new Map<string, number>();
    let read = 0;
    for await (const row of lines) {
      read++;
      if (read === 1) continue;
      // PuzzleId,FEN,Moves,Rating,RatingDeviation,Popularity,NbPlays,Themes,GameUrl,OpeningTags
      const [, fen = '', movesRaw = '', ratingRaw = '0', dev = '999', pop = '0', plays = '0', tags = ''] =
        row.split(',');
      const rating = Number(ratingRaw);
      const moves = movesRaw.split(' ');
      if (rating < LOW || rating >= HIGH || moves.length < 2 || moves.length > 6) continue;
      if (Number(dev) > 85 || Number(pop) < 85 || Number(plays) < 300) continue;
      const band = Math.floor(rating / 100);
      const list = bands.get(band) ?? [];
      if (list.length >= PER_BAND) continue;
      const tagList = tags.split(' ');
      const theme = THEMES.find(([tag]) => tagList.includes(tag))?.[1] ?? 'tactic';
      const tk = `${band}:${theme}`;
      if ((themeCount.get(tk) ?? 0) >= PER_THEME) continue;
      // the opponent's move first, then the puzzle starts
      const p = fromFen(fen);
      const first = moveOf(p, moves[0] ?? '');
      if (!first) continue;
      makeMove(p, first);
      const start = fullFen(p);
      // the whole solution must be legal here
      const q = fromFen(start);
      if (
        !moves.slice(1).every((u) => {
          const m = moveOf(q, u);
          if (m) makeMove(q, m);
          return m !== 0;
        })
      )
        continue;
      const black = p.side === -1;
      const outFen = black ? mirrorFen(start) : start;
      const line = moves.slice(1).map((u) => (black ? mirrorUci(u) : u));
      list.push({ line: `${outFen}|${line.join(' ')}|${rating}|${theme}`, rating });
      bands.set(band, list);
      themeCount.set(tk, (themeCount.get(tk) ?? 0) + 1);
      const full = [...bands.values()].reduce((a, b) => a + b.length, 0);
      if (full >= ((HIGH - LOW) / 100) * PER_BAND) break;
    }
    const keep = [...bands.values()].flat().sort((a, b) => a.rating - b.rating);
    writeFileSync(
      'src/core/chessPuzzles.ts',
      [
        '// Generated by tests/sim/chess-import.sim.ts (`npm run chess:import`). Do not edit by hand.',
        '// Puzzles from the Lichess puzzle database (https://database.lichess.org/#puzzles), public domain',
        '// (CC0). Each: "FEN (White to move)|solution in long algebraic, your moves and the replies|rating|theme".',
        'export const PUZZLES: readonly string[] = [',
        ...keep.map((k) => `  '${k.line}',`),
        '];',
        '',
      ].join(NL),
    );
    console.log(`read ${read} rows, kept ${keep.length}`);
  });
});
