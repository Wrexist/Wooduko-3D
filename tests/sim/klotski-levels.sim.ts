// Builds the Workshop Klotski levels and writes src/core/klotskiLevels.ts.
// `npm run klotski:levels` (about a minute). Deterministic: same seed, same levels.
//
// Random 4×5 layouts (a 2×2 key piece near the top plus a mix of 1×2, 2×1 and 1×1 blocks) are solved
// with the breadth-first solver; layouts are bucketed by their fewest-moves par and one is kept per
// target par, so difficulty climbs smoothly. The classic "Forget-me-not" layout closes the set.
import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { parseLevel, solve } from '../../src/core/klotski';

const W = 4;
const H = 5;
const LEVELS = 30;

function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Piece sets from loose to tight: [verticals 1×2, horizontals 2×1, singles 1×1]. */
const SETS: readonly [number, number, number][] = [
  [2, 1, 2],
  [2, 2, 2],
  [3, 1, 3],
  [4, 0, 4],
  [3, 2, 3],
  [4, 1, 3],
  [4, 1, 4],
];

function layout(rand: () => number, set: [number, number, number]): string[] | null {
  const g: string[][] = Array.from({ length: H }, () => Array<string>(W).fill('.'));
  const free = (r: number, c: number, w: number, h: number): boolean => {
    if (r + h > H || c + w > W) return false;
    for (let y = r; y < r + h; y++) for (let x = c; x < c + w; x++) if (g[y]?.[x] !== '.') return false;
    return true;
  };
  const put = (ch: string, r: number, c: number, w: number, h: number): void => {
    for (let y = r; y < r + h; y++) for (let x = c; x < c + w; x++) (g[y] as string[])[x] = ch;
  };
  // key piece in the top two rows, never already over the exit
  const kr = Math.floor(rand() * 2);
  const kc = Math.floor(rand() * 3);
  put('A', kr, kc, 2, 2);
  const shapes: [number, number][] = [
    ...Array<[number, number]>(set[0]).fill([1, 2]),
    ...Array<[number, number]>(set[1]).fill([2, 1]),
    ...Array<[number, number]>(set[2]).fill([1, 1]),
  ];
  let letter = 66; // 'B'
  for (const [w, h] of shapes) {
    const spots: [number, number][] = [];
    for (let r = 0; r < H; r++) for (let c = 0; c < W; c++) if (free(r, c, w, h)) spots.push([r, c]);
    if (!spots.length) return null;
    const [r, c] = spots[Math.floor(rand() * spots.length)] as [number, number];
    put(String.fromCharCode(letter++), r, c, w, h);
  }
  return g.map((row) => row.join(''));
}

const CLASSIC = ['BAAC', 'BAAC', 'DEEF', 'DGHF', 'I..J'];

describe('klotski levels', () => {
  it('writes the level table', () => {
    const rand = rng(20261013);
    const byPar = new Map<number, string[]>();
    for (let i = 0; i < 6000; i++) {
      const set = SETS[Math.min(SETS.length - 1, Math.floor((i / 6000) * SETS.length))] as [number, number, number];
      const rows = layout(rand, set);
      if (!rows) continue;
      const par = solve(parseLevel(rows), undefined, 200_000);
      if (par < 3) continue;
      if (!byPar.has(par)) byPar.set(par, rows);
    }
    const pars = [...byPar.keys()].sort((a, b) => a - b);
    const top = pars.at(-1) ?? 3;
    const picked: { rows: string[]; par: number }[] = [];
    const used = new Set<number>();
    // targets climb from 3 moves to the hardest found, faster at first
    for (let n = 0; n < LEVELS - 1; n++) {
      const target = 3 + (top - 3) * Math.pow(n / (LEVELS - 2), 1.4);
      const best = pars.filter((p) => !used.has(p)).sort((a, b) => Math.abs(a - target) - Math.abs(b - target))[0];
      if (best === undefined) break;
      used.add(best);
      picked.push({ rows: byPar.get(best) as string[], par: best });
    }
    picked.sort((a, b) => a.par - b.par);
    picked.push({ rows: CLASSIC, par: solve(parseLevel(CLASSIC), undefined, 1_000_000) });
    const body = picked.map((l) => `  { rows: ${JSON.stringify(l.rows)}, par: ${l.par} },`).join('\n');
    writeFileSync(
      'src/core/klotskiLevels.ts',
      `// Generated by \`npm run klotski:levels\` (tests/sim/klotski-levels.sim.ts). Do not edit by hand.\n` +
        `// par = fewest moves (one move = one straight slide of one piece).\n` +
        `export const KLOTSKI_LEVELS: readonly { readonly rows: readonly string[]; readonly par: number }[] = [\n${body}\n];\n`,
    );
    console.log(picked.map((l) => l.par).join(' '));
  });
});
